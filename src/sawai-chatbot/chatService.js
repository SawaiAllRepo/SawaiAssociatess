// --------------------------------------------------

export function trackEvent(eventType) {
  if (CHATBOT_DEMO_MODE || !CHATBOT_API_CONFIGURED) {
    return;
  }

  const sessionId = getSessionId();

  const payload = sessionId
    ? {
        event_type: eventType,
        session_id: sessionId,
      }
    : {
        event_type: eventType,
      };

  fetch(CHATBOT_ANALYTICS_URL, {
    method: "POST",
    headers: {
      "Content-Type": "application/json",
    },
    body: JSON.stringify(payload),
  }).catch(() => {
    // Analytics must never interrupt the conversation.
  });
}

// --------------------------------------------------
// GOOGLE SHEETS CHATBOT LEAD INTEGRATION
// --------------------------------------------------

// Prevent repeated requests for the same lead
// during the current browser page session.
const submittedLeadIds = new Set();

function normalizeLeadDetails(summary) {
  const details = {};

  if (!Array.isArray(summary)) {
    return details;
  }

  for (const item of summary) {
    if (
      typeof item?.label !== "string" ||
      typeof item?.value !== "string"
    ) {
      continue;
    }

    const key = item.label
      .trim()
      .toLowerCase()
      .replace(/[^a-z0-9]+/g, "_");

    if (key) {
      details[key] = item.value.trim();
    }
  }

  return details;
}

function formatConversation(transcript) {
  if (!Array.isArray(transcript)) {
    return "";
  }

  return transcript
    .filter(
      (message) =>
        message &&
        (message.role === "user" || message.role === "bot")
    )
    .map((message) => {
      const role =
        message.role === "user" ? "Visitor" : "Assistant";

      return `${role}: ${String(message.text || "")}`;
    })
    .join("\n")
    .slice(0, 45000);
}

// Call this only after the chatbot backend confirms
// that the customer's lead was created.
export async function mirrorConfirmedLead(data, transcript = []) {
  if (CHATBOT_DEMO_MODE) {
    return false;
  }

  if (
    data?.lead_created !== true ||
    !data?.lead_id ||
    !data?.session_id
  ) {
    return false;
  }

  if (!SHEETS_WEB_APP_URL) {
    console.warn(
      "Google Sheets integration not configured: VITE_SHEETS_WEB_APP_URL is missing."
    );
    return false;
  }

  const leadId = String(data.lead_id);

  if (submittedLeadIds.has(leadId)) {
    return false;
  }

  const details = normalizeLeadDetails(data.summary);

  const leadPayload = {
    type: "chatbot_lead",
    id:
      typeof crypto !== "undefined" &&
      typeof crypto.randomUUID === "function"
        ? crypto.randomUUID()
        : `${Date.now()}-${Math.random().toString(36).slice(2)}`,
    data: {
      lead_id: leadId,
      session_id: String(data.session_id),
      service: String(data.service || ""),
      details,
      conversation: formatConversation(transcript),
      source: "Website Chatbot",
    },
  };

  try {
    // Compatible with a Google Apps Script Web App
    // accepting a JSON string as text/plain.
    // no-cors does not expose the server response.
    await fetch(SHEETS_WEB_APP_URL, {
      method: "POST",
      mode: "no-cors",
      headers: {
        "Content-Type": "text/plain",
      },
      body: JSON.stringify(leadPayload),
    });

    submittedLeadIds.add(leadId);

    console.info(
      "Chatbot lead request sent to Google Apps Script. Sheet insertion is not confirmed."
    );

    return true;
  } catch (error) {
    console.error(
      "Could not send chatbot lead to Google Sheets:",
      error
    );

    return false;
  }
}
