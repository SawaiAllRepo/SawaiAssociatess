
import {
  CHATBOT_ANALYTICS_URL,
  CHATBOT_API_CONFIGURED,
  CHATBOT_API_URL,
  CHATBOT_DEMO_MODE,
} from "./apiConfig";

const REQUEST_TIMEOUT_MS = 60000;
export const MAX_MESSAGE_LENGTH = 2000;

const SESSION_KEY = "sawai_chat_session_id";

// Google Apps Script Web App URL
// Set this in your Vite environment configuration.
const SHEETS_WEB_APP_URL = (
  import.meta.env.VITE_SHEETS_WEB_APP_URL || ""
).trim();

const DEMO_OPTIONS = [
  "Real Estate",
  "Insurance",
  "IT Services",
  "Ask a Question",
];

export const storage = {
  get(key) {
    try {
      return localStorage.getItem(key);
    } catch {
      return null;
    }
  },

  set(key, value) {
    try {
      localStorage.setItem(key, value);
    } catch {
      // Storage errors must not interrupt chatting.
    }
  },

  remove(key) {
    try {
      localStorage.removeItem(key);
    } catch {
      // Storage may be unavailable.
    }
  },
};

export const getSessionId = () => storage.get(SESSION_KEY);

export const clearSession = () => storage.remove(SESSION_KEY);

// --------------------------------------------------
// DEMO CHATBOT
// --------------------------------------------------

async function simulateChat(payload) {
  await new Promise((resolve) => setTimeout(resolve, 650));

  const message =
    typeof payload.message === "string"
      ? payload.message.trim()
      : "";

  if (message.toLowerCase() === "/demo-error") {
    throw new Error(
      "[SIMULATED DEMO ERROR] This error is local and did not come from the chatbot backend."
    );
  }

  const reply = payload.action
    ? `[SIMULATED DEMO REPLY] The ${payload.action} action was displayed for UI testing only. No consent or lead action was sent.`
    : "[SIMULATED DEMO REPLY] Your message was received by the local UI demo. This is not generated by the AI backend.";

  return {
    reply,
    menu_options: DEMO_OPTIONS,
    actions: [],
  };
}

// --------------------------------------------------
// MAIN CHATBOT API
// --------------------------------------------------

export async function postChat(payload) {
  if (CHATBOT_DEMO_MODE) {
    return simulateChat(payload);
  }

  if (!CHATBOT_API_CONFIGURED) {
    throw new Error(
      "Chatbot is not configured. Set VITE_CHATBOT_API_BASE_URL to the deployed chatbot API origin."
    );
  }

  const sessionId = getSessionId();

  const body = sessionId
    ? { ...payload, session_id: sessionId }
    : payload;

  const controller = new AbortController();

  const timer = setTimeout(
    () => controller.abort(),
    REQUEST_TIMEOUT_MS
  );

  let response;

  try {
    response = await fetch(CHATBOT_API_URL, {
      method: "POST",
      headers: {
        "Content-Type": "application/json",
      },
      body: JSON.stringify(body),
      signal: controller.signal,
    });
  } catch (error) {
    throw new Error(
      error?.name === "AbortError"
        ? "Sorry, that's taking longer than usual. Please try again in a moment."
        : "I can't reach the chatbot server right now. Please try again later."
    );
  } finally {
    clearTimeout(timer);
  }

  let data = null;

  try {
    data = await response.json();
  } catch {
    data = null;
  }

  if (!response.ok) {
    if (typeof data?.detail === "string") {
      throw new Error(data.detail);
    }

    if (response.status === 429) {
      throw new Error(
        "Please wait a moment before sending another message."
      );
    }

    if (response.status === 422) {
      throw new Error(
        "I couldn't read that message. Could you rephrase it?"
      );
    }

    throw new Error(
      "Sorry, something went wrong. Please try again."
    );
  }

  if (
    !data ||
    typeof data.reply !== "string" ||
    !data.reply.trim() ||
    typeof data.session_id !== "string" ||
    !data.session_id.trim()
  ) {
    throw new Error(
      "The chatbot server returned an invalid response. Please try again."
    );
  }

  storage.set(SESSION_KEY, data.session_id);

  return data;
}

